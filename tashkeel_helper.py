def strip_existing_tashkeel(text):
    tashkeel_chars = '\u064B\u064C\u064D\u064E\u064F\u0650\u0651\u0652\u0653\u0654\u0655\u0656\u0657\u0658\u0670'
    return ''.join(c for c in text if c not in tashkeel_chars)

def tashkeel_word(word):
    clean_word = strip_existing_tashkeel(word)
    if clean_word in COMMON_WORDS:
        return COMMON_WORDS[clean_word]
    return word

def tashkeel_text(text):
    tokens = re.split(r'(\s+|[.,!?؟،:؛])', text)
    result = []
    for token in tokens:
        if not token.strip() or token in '.,!?؟،:؛':
            result.append(token)
        else:
            result.append(tashkeel_word(token))
    return ''.join(result)

def add_tashkeel_to_text(text):
    try:
        return tashkeel_text(text)
    except Exception as e:
        print(f"Tashkeel error: {e}")
        return text

